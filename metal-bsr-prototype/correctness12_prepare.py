#!/usr/bin/env python3
"""Choose the Clover action from the new gauge header, preserving its digits."""
import hashlib
import json
import struct
import xml.etree.ElementTree as ET
import argparse
from decimal import Decimal
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--gauge', type=Path)
parser.add_argument('--mass', help='explicit header mass when the ensemble has several flavors')
parser.add_argument('--out-dir', type=Path, default=Path('results/correctness12'))
args = parser.parse_args()
data = Path('/Users/admin/Downloads/download/prop_tests')
matches = [args.gauge] if args.gauge else list(data.glob('*_12_96_*cfg*.lime'))
if len(matches) != 1:
    raise RuntimeError('expected exactly one 12^3 x 96 LIME configuration')
gauge = matches[0]
records = {}
with gauge.open('rb') as stream:
    while header := stream.read(144):
        magic, version, flags, size, tag = struct.unpack('>IHHQ128s', header)
        if magic != 0x456789ab:
            raise ValueError('bad LIME magic')
        name = tag.split(b'\0', 1)[0].decode()
        if 'xml' in name or 'format' in name or 'checksum' in name:
            records[name] = stream.read(size).rstrip(b'\0 \t\r\n')
        else:
            stream.seek(size, 1)
        stream.seek((-size) % 8, 1)
record = ET.fromstring(records['scidac-record-xml'])
shape = list(map(int, record.findtext('./HMCTrj/nrow').split()))
assert len(shape) == 4 and all(n > 0 and n % 2 == 0 for n in shape)
actions = record.findall('.//FermionAction')
available_masses = sorted({a.findtext('Mass').strip() for a in actions})
if args.mass is not None:
    actions = [a for a in actions if Decimal(a.findtext('Mass')) == Decimal(args.mass)]
if not actions:
    raise ValueError('requested mass absent from gauge header')
fields = ['FermAct', 'Mass', 'clovCoeffR', 'clovCoeffT',
          'AnisoParam/anisoP', 'AnisoParam/xi_0', 'AnisoParam/nu', 'AnisoParam/t_dir',
          'FermState/Name', 'FermState/rho', 'FermState/n_smear',
          'FermState/orthog_dir', 'FermState/FermionBC/FermBC',
          'FermState/FermionBC/boundary']
signatures = {tuple(a.findtext(k).strip() for k in fields) for a in actions}
if len(signatures) != 1:
    raise ValueError('gauge header contains differing fermion actions; choose explicitly')
root = ET.Element('DBMetaData')
ET.SubElement(root, 'lattSize').text = ' '.join(map(str, shape))
params = ET.SubElement(root, 'Params')
ET.SubElement(params, 'Propagator').append(actions[0])
times = ET.SubElement(params, 'Contractions')
ET.SubElement(times, 't_sources').text = '0'
ET.SubElement(times, 'Nt_forward').text = '1'
out = args.out_dir; out.mkdir(parents=True, exist_ok=True)
ET.indent(root)
ET.ElementTree(root).write(out/'action.xml', encoding='utf-8', xml_declaration=True)
for name, contents in records.items():
    (out/(name+'.xml')).write_bytes(contents)
info = dict(zip(fields, next(iter(signatures))))
info.update({'gauge': str(gauge), 'shape': shape,
             'gauge_sha256': hashlib.sha256(gauge.read_bytes()).hexdigest(),
             'agreeing_header_actions': len(actions), 'random_seed': 20261107,
             'available_header_masses': available_masses,
             'selected_mass_argument': args.mass,
             'source': 'unit-norm dense complex Z4, generated by SplitMix64 component hashing',
             'full_relative_residual_tolerance': 1e-12,
             'note': 'Action values come from this gauge header, not the older 24^3 perambulator. Dummy contraction times in action.xml are unused for this random-source test.'})
(out/'input.json').write_text(json.dumps(info, indent=2)+'\n')
print(json.dumps(info, indent=2))
